export const seedGraph = (): GraphData => {
  const nodes = Object.fromEntries(baseNodes.map((node) => [node.id, { ...node }])) as GraphData['nodes'];

  return {
    nodes,
    edges: baseNodes
      .filter((node) => node.parentId)
      .map((node) => ({
        id: `${node.parentId}-${node.id}`,
        source: node.parentId!,
        target: node.id,
      })),
    rootIds: baseNodes.filter((node) => node.parentId === null).map((node) => node.id),
  };
};

